#!/usr/bin/env bash
# Build the deployable Soroban contracts to wasm32-unknown-unknown release
# artifacts using the toolchain pinned in rust-toolchain.toml and the
# workspace lockfile.
#
# Usage:
#   scripts/build_wasm.sh            # builds credit-engine + auction
#   scripts/build_wasm.sh credit     # builds only creditra-credit
#   scripts/build_wasm.sh auction    # builds only gateway-auction
#   scripts/build_wasm.sh --check    # verify existing artifacts, no build
#
# Output: target/wasm32-unknown-unknown/release/*.wasm
set -euo pipefail

cd "$(dirname "$0")/.."

TARGET="wasm32-unknown-unknown"
PROFILE="release"
WASM_DIR="target/${TARGET}/${PROFILE}"
CREDIT_WASM="${WASM_DIR}/creditra_credit.wasm"
AUCTION_WASM="${WASM_DIR}/gateway_auction.wasm"
SELECTOR="all"
CHECK_ONLY=0

while [[ $# -gt 0 ]]; do
    case "$1" in
        --check | --check-only)
            CHECK_ONLY=1
            shift
            ;;
        all | credit | auction)
            SELECTOR="$1"
            shift
            ;;
        -h | --help)
            sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
            exit 0
            ;;
        *)
            echo "unknown argument: $1" >&2
            echo "expected one of: all, credit, auction, --check" >&2
            exit 64
            ;;
    esac
done

# Reproducible builds need the lockfile to be present and committed. It is
# generated by Cargo and checked in so dependency resolution cannot drift
# between a developer machine and CI.
if [[ ! -f Cargo.lock ]]; then
    echo "::error::Cargo.lock is missing; reproducible builds require the committed lockfile" >&2
    exit 1
fi

if ! rustup target list --installed 2>/dev/null | grep -qx "$TARGET"; then
    echo "::error::Rust target ${TARGET} is not installed." >&2
    echo "Install it with: rustup target add ${TARGET}" >&2
    exit 1
fi

build_one() {
    local package="$1"
    echo "Building ${package} (${TARGET}, ${PROFILE})..."
    cargo build --locked --target "$TARGET" --profile "$PROFILE" -p "$package"
}

if [[ "$CHECK_ONLY" -eq 0 ]]; then
    case "$SELECTOR" in
        all)
            build_one creditra-credit
            build_one gateway-auction
            ;;
        credit)
            build_one creditra-credit
            ;;
        auction)
            build_one gateway-auction
            ;;
    esac
fi

check_artifact() {
    local path="$1"
    if [[ ! -f "$path" ]]; then
        echo "::error::Expected WASM artifact not found: ${path}" >&2
        exit 1
    fi
}

case "$SELECTOR" in
    all)
        check_artifact "$CREDIT_WASM"
        check_artifact "$AUCTION_WASM"
        ;;
    credit)
        check_artifact "$CREDIT_WASM"
        ;;
    auction)
        check_artifact "$AUCTION_WASM"
        ;;
esac

echo
echo "WASM artifacts:"
for path in "$CREDIT_WASM" "$AUCTION_WASM"; do
    [[ -f "$path" ]] || continue
    size="$(wc -c <"$path" | tr -d '[:space:]')"
    digest="$(sha256sum "$path" | awk '{print $1}')"
    printf '  %-52s %8s bytes  sha256=%s\n' "$path" "$size" "$digest"
done
